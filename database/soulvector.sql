-- SoulVector MVP schema for Supabase PostgreSQL + pgvector.
-- The local embedding model is bge-m3, which returns 1024-dimensional vectors.

create schema if not exists extensions;
create extension if not exists vector with schema extensions;

create table if not exists public.sv_profiles (
  profile_id uuid primary key,
  display_name text not null,
  is_discoverable boolean not null default true,
  embedding extensions.vector(1024) not null,
  embedding_model text not null default 'bge-m3',
  -- Separate 640-dimensional Russian stylometric fingerprint (v3).
  author_style_embedding extensions.vector(640),
  style_version text,
  style_word_count integer,
  style_metrics jsonb,
  reasoning_embedding extensions.vector(12),
  reasoning_version text,
  reasoning_analysis jsonb,
  poem_count smallint not null check (poem_count between 1 and 5),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_analyzed_at timestamptz not null default now()
);

create table if not exists public.sv_poems (
  id bigint generated always as identity primary key,
  profile_id uuid not null references public.sv_profiles(profile_id) on delete cascade,
  client_poem_id text not null,
  title varchar(160) not null,
  body text not null,
  embedding extensions.vector(1024) not null,
  embedding_model text not null default 'bge-m3',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (profile_id, client_poem_id)
);

create index if not exists sv_profiles_discoverable_idx
  on public.sv_profiles (is_discoverable, embedding_model);

create index if not exists sv_profiles_embedding_hnsw_idx
  on public.sv_profiles using hnsw (embedding extensions.vector_cosine_ops);

create index if not exists sv_profiles_author_style_hnsw_idx
  on public.sv_profiles using hnsw (author_style_embedding extensions.vector_cosine_ops)
  where author_style_embedding is not null;

create index if not exists sv_profiles_reasoning_hnsw_idx
  on public.sv_profiles using hnsw (reasoning_embedding extensions.vector_l2_ops)
  where reasoning_embedding is not null;

create index if not exists sv_poems_profile_id_idx
  on public.sv_poems (profile_id);

comment on table public.sv_profiles is
  'SoulVector user literary profiles. The embedding is a semantic text profile, not a psychological diagnosis.';

comment on table public.sv_poems is
  'Poems and their per-poem bge-m3 embeddings for a SoulVector profile.';

comment on column public.sv_profiles.author_style_embedding is
  'Experimental 640D Russian stylometric fingerprint: 80 surface statistics, 128 morphology features, 432 hashed character n-grams; not a personality or cognition measurement.';

comment on column public.sv_profiles.reasoning_embedding is
  '12D rubric vector of observable reasoning patterns present in poem texts, generated by local Ollama LLM; not a validated measure of personality or actual cognition.';
