-- SoulVector stage 2: local LLM-based, text-grounded reasoning-pattern profile.
-- Apply after migrations 003_russian_stylometry_v2.sql and 004_russian_stylometry_v3.sql.
-- Existing semantic embeddings and poem rows are preserved. Profiles need re-analysis
-- before they can participate in the three-component ranking.

ALTER TABLE public.sv_profiles
  ADD COLUMN IF NOT EXISTS reasoning_embedding extensions.vector(12),
  ADD COLUMN IF NOT EXISTS reasoning_version text,
  ADD COLUMN IF NOT EXISTS reasoning_analysis jsonb;

CREATE INDEX IF NOT EXISTS sv_profiles_reasoning_hnsw_idx
  ON public.sv_profiles
  USING hnsw (reasoning_embedding extensions.vector_l2_ops)
  WHERE reasoning_embedding IS NOT NULL;

COMMENT ON COLUMN public.sv_profiles.reasoning_embedding IS
  '12D rubric vector of observable reasoning patterns present in poem texts, generated by local Ollama LLM. Not a validated measurement of actual cognition or personality.';

COMMENT ON COLUMN public.sv_profiles.reasoning_analysis IS
  'Structured, evidence-grounded text analysis, including feature scores and checked quote excerpts.';
